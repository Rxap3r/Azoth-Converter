"""Builds docs/FORMATS.md, the list of supported formats and conversions.

The list is generated from the converters themselves, so it can't drift from
what the app really does. Regenerate it with:

    fileconv formats --markdown docs/FORMATS.md

A test fails if the committed file is out of date.
"""

from __future__ import annotations

from . import formats
from .engine import Engine

CATEGORY_TITLES = {
    formats.DOCUMENT: "Text documents",
    formats.PDF: "PDF",
    formats.SPREADSHEET: "Spreadsheets",
    formats.PRESENTATION: "Presentations",
    formats.IMAGE: "Images",
}
CATEGORY_NOTES = {
    formats.PDF: [
        "PDF → image creates one image per page (`name_page001.png`, …). "
        "TIFF puts all pages into one multi-page file.",
        "PDF → Word rebuilds an editable layout. Scanned PDFs (pictures of pages) "
        "need text recognition (OCR), which is planned.",
        "Password-protected PDFs must be unlocked first.",
    ],
    formats.DOCUMENT: [
        "Word → image goes through PDF and creates one image per page.",
    ],
    formats.SPREADSHEET: [
        "CSV keeps only the first sheet, without formatting.",
    ],
    formats.PRESENTATION: [
        "Presentation → image creates one image per slide.",
    ],
    formats.IMAGE: [
        "Photo metadata (camera, date, GPS location) is removed by default.",
        "Formats without transparency (JPG, BMP, PDF) get a white background.",
        "Animated GIF/WebP and multi-page TIFF keep all frames when the target supports it.",
    ],
}
LIBREOFFICE_ID = "libreoffice"


def _names(fmts: list[formats.Format]) -> str:
    return ", ".join(f.id.upper() for f in fmts) if fmts else "–"


def build_markdown(engine: Engine | None = None) -> str:
    full = engine or Engine()
    if any(c.id == LIBREOFFICE_ID for c in full.unavailable()):
        raise RuntimeError("Install LibreOffice to generate the complete format list.")
    basic = Engine([c for c in full.converters if c.id != LIBREOFFICE_ID])

    lines = [
        "# Supported formats",
        "",
        "<!-- Generated by `fileconv formats --markdown docs/FORMATS.md`. Don't edit by hand. -->",
        "",
        "Everything is converted on your computer. Nothing is uploaded.",
        "",
        "Most office formats need the free [LibreOffice](https://www.libreoffice.org/download/) "
        "to be installed. The column **Works right away** lists what works without it.",
        "",
        "## All formats",
        "",
        "| Format | File extensions | Type |",
        "|--------|-----------------|------|",
    ]
    for fmt in formats.FORMATS.values():
        exts = ", ".join(f".{e}" for e in fmt.extensions)
        kind = CATEGORY_TITLES[fmt.category]
        lines.append(f"| **{fmt.id.upper()}**: {fmt.name} | {exts} | {kind} |")

    for category, title in CATEGORY_TITLES.items():
        lines += [
            "",
            f"## {title}",
            "",
            "| From | Works right away | Also with LibreOffice installed |",
            "|------|------------------|--------------------------------|",
        ]
        for fmt in formats.FORMATS.values():
            if fmt.category != category:
                continue
            everything = full.targets_for(fmt.id)
            right_away = {t.id for t in basic.targets_for(fmt.id)}
            with_lo = [t for t in everything if t.id not in right_away]
            without_lo = [t for t in everything if t.id in right_away]
            lines.append(f"| **{fmt.id.upper()}** | {_names(without_lo)} | {_names(with_lo)} |")
        notes = CATEGORY_NOTES.get(category, [])
        if notes:
            lines.append("")
            lines += [f"- {note}" for note in notes]

    lines += [
        "",
        "## Also available",
        "",
        "- **Merge PDFs:** `fileconv pdf merge a.pdf b.pdf -o combined.pdf`",
        "- **Split a PDF into single pages:** `fileconv pdf split file.pdf`",
        "",
        "Planned formats (audio, video, e-books, archives, …) are listed in the "
        "[project plan](PROJECT_PLAN.md).",
        "",
    ]
    return "\n".join(lines)
