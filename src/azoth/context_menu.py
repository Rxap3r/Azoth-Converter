"""The Windows Explorer right-click menu, written as Inno Setup registry entries.

Right-click a file → "Convert with Azoth Converter" → "To PDF", "To DOCX" … (the most
useful targets for that kind of file), "Remove metadata" where that works, and "Open in
Azoth Converter". The installer adds the entries (task "Add to the right-click menu")
and removes them again on uninstall; the app itself never writes to the registry.

The entries are generated, not written by hand, so they always match what the app can
do: ``python packaging/make_context_menu.py`` writes ``packaging/context_menu.iss``
(a test checks that the file is up to date).

They are "classic" menu entries: on Windows 11 they appear under "Show more options"
(or Shift+F10). Windows 11's short menu only accepts entries from signed app packages,
which needs code signing first.
"""

from __future__ import annotations

from dataclasses import dataclass

from . import formats, metadata
from .engine import Engine
from .gui.explorer import OPEN
from .gui.targets import CLEAN_TARGET, display_name

MENU_KEY = "AzothConverter"
MENU_TITLE = "Convert with Azoth Converter"
MAX_TARGETS = 6  # more would make a long menu; "Open in Azoth Converter" offers all
EXE = r"{app}\AzothConverter.exe"
TASK = "contextmenu"
SEPARATOR_BEFORE = 0x20  # ECF_SEPARATORBEFORE


@dataclass(frozen=True)
class Entry:
    key: str  # sub key name; Explorer sorts the entries by it
    label: str
    target: str
    separator: bool = False


def entries_for(fmt: formats.Format, engine: Engine) -> list[Entry]:
    """The menu for one kind of file (empty: no menu)."""
    entries = [
        Entry(f"{i + 1:02d}{target.id}", f"To {display_name(target.id)}", target.id)
        for i, target in enumerate(engine.targets_for(fmt.id)[:MAX_TARGETS])
    ]
    if fmt.id in metadata.CLEANABLE:
        entries.append(Entry("80clean", "Remove metadata", CLEAN_TARGET, separator=True))
    if not entries:
        return []
    entries.append(
        Entry(
            "90open", "Open in Azoth Converter…", OPEN, separator=fmt.id not in metadata.CLEANABLE
        )
    )
    return entries


def menus(engine: Engine | None = None) -> dict[str, list[Entry]]:
    """File extension (``.docx``) → menu entries. Every engine counts as installed: the
    menu is made once, when the installer is built; a conversion that needs a missing
    engine shows the app's usual message."""
    from .converters import all_converters

    engine = engine or Engine(all_converters(), assume_available=True)
    result = {}
    for fmt in formats.FORMATS.values():
        entries = entries_for(fmt, engine)
        for ext in fmt.extensions:
            if entries:
                result[f".{ext}"] = entries
    return dict(sorted(result.items()))


def _q(text: str) -> str:
    """A string for an Inno Setup value: quotes doubled."""
    return text.replace('"', '""')


def iss_text(engine: Engine | None = None) -> str:
    lines = [
        "; Generated by packaging/make_context_menu.py from the app's formats. Don't edit:",
        "; run `python packaging/make_context_menu.py` after changing conversions.",
        "; The Explorer right-click menu (see src/azoth/context_menu.py). Each kind of file",
        "; gets its own menu. Old entries are always removed first, so an update (or",
        "; unticking the task) never leaves stale entries behind.",
    ]
    task = f"Tasks: {TASK}"
    for ext, entries in menus(engine).items():
        base = rf"Software\Classes\SystemFileAssociations\{ext}"
        menu = rf"{base}\shell\{MENU_KEY}"
        lines.append(f'Root: HKA; Subkey: "{menu}"; Flags: deletekey dontcreatekey uninsdeletekey')
        lines.append(f'Root: HKA; Subkey: "{base}"; Flags: uninsdeletekeyifempty; {task}')
        lines.append(rf'Root: HKA; Subkey: "{base}\shell"; Flags: uninsdeletekeyifempty; {task}')
        lines += [
            f'Root: HKA; Subkey: "{menu}"; ValueType: string; ValueName: "MUIVerb"; '
            f'ValueData: "{MENU_TITLE}"; {task}',
            f'Root: HKA; Subkey: "{menu}"; ValueType: string; ValueName: "Icon"; '
            f'ValueData: "{EXE},0"; {task}',
            f'Root: HKA; Subkey: "{menu}"; ValueType: string; ValueName: "SubCommands"; '
            f'ValueData: ""; {task}',
            # Show the menu also when many files are selected (Explorer hides it above 15).
            f'Root: HKA; Subkey: "{menu}"; ValueType: string; ValueName: "MultiSelectModel"; '
            f'ValueData: "Player"; {task}',
        ]
        for entry in entries:
            key = rf"{menu}\shell\{entry.key}"
            command = _q(f'"{EXE}" --explorer {entry.target} "%1"')
            lines.append(
                f'Root: HKA; Subkey: "{key}"; ValueType: string; ValueName: "MUIVerb"; '
                f'ValueData: "{_q(entry.label)}"; {task}'
            )
            if entry.separator:
                lines.append(
                    f'Root: HKA; Subkey: "{key}"; ValueType: dword; ValueName: "CommandFlags"; '
                    f"ValueData: ${SEPARATOR_BEFORE:x}; {task}"
                )
            lines.append(
                rf'Root: HKA; Subkey: "{key}\command"; ValueType: string; ValueName: ""; '
                f'ValueData: "{command}"; {task}'
            )
    return "\n".join(lines) + "\n"
